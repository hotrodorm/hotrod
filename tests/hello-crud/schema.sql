CREATE TABLE employee (
  id INT GENERATED BY DEFAULT AS IDENTITY (START WITH 500) PRIMARY KEY NOT NULL,
  first_name VARCHAR(20),
  last_name VARCHAR(20) NOT NULL,
  salary INT,
  branch_id INT DEFAULT 101
);

