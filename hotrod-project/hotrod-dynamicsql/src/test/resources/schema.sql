CREATE TABLE employee (
  id INT GENERATED BY DEFAULT AS IDENTITY (START WITH 200) PRIMARY KEY NOT NULL,
  first_name VARCHAR(20),
  last_name VARCHAR(20),
  last_ssn VARCHAR(20),
  hired_on DATE,
  salary INT,
  dept_no INT,
  active CHAR(1) DEFAULT 'Y' CHECK (active IN ('Y', 'N'))
);

