package org.hotrod.dynamicsql.tuples;

public class DTuple2<A, B> {

  protected A a;
  protected B b;

  public final A getA() {
    return a;
  }

  public final void setA(A a) {
    this.a = a;
  }

  public final B getB() {
    return b;
  }

  public final void setB(B b) {
    this.b = b;
  }

}
