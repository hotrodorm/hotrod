package org.hotrod.utils;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertThrows;

import java.io.IOException;

import org.hotrod.BuildInformation;
import org.hotrod.config.Constants;
import org.hotrod.generator.FileGenerator.TextWriter;
import org.hotrod.metadata.TypeParser;
import org.hotrod.utils.AbstractClassWriter.ExternalClass;
import org.junit.jupiter.api.Test;

public class AbstractClassWriterTest {

  @Test
  public void writesGeneratedCommentHeadersPackageAndSegments() throws Exception {
    AbstractClassWriter writer = new AbstractClassWriter(ClassPackage.parse("example.generated"), true, "// header",
        "// another header");
    writer.segments.add("class Example {}\n");
    writer.println();

    assertEquals("// Generated by " + Constants.TOOL_NAME + " " + BuildInformation.VERSION + " - Do not edit\n\n"
        + "// header\n// another header\npackage example.generated;\n\nclass Example {}\n\n", render(writer));
  }

  @Test
  public void simpleResolution1() throws Exception {

    JULCustomFormatter.initialize(java.util.logging.Level.INFO);

    AbstractClassWriter writer = new AbstractClassWriter(ClassPackage.parse("example"), false, (String[]) null);
    assertEquals("List", writer.registerClass(ExternalClass.of("com.app.List")));
    assertEquals("java.util.List", writer.registerClass(ExternalClass.of("java.util.List")));
    assertEquals("List", writer.registerClass(ExternalClass.of("com.app.List")));
    assertEquals("java.util.List", writer.registerClass(ExternalClass.of("java.util.List")));

    writer = new AbstractClassWriter(ClassPackage.parse("example"), false, (String[]) null);
    assertEquals("List", writer.registerClass(ExternalClass.of("java.util.List")));
    assertEquals("com.app.List", writer.registerClass(ExternalClass.of("com.app.List")));
    assertEquals("List", writer.registerClass(ExternalClass.of("java.util.List")));
    assertEquals("com.app.List", writer.registerClass(ExternalClass.of("com.app.List")));
  }

  @Test
  public void javaLangResolution() throws Exception {

    JULCustomFormatter.initialize(java.util.logging.Level.INFO);

    AbstractClassWriter writer = new AbstractClassWriter(ClassPackage.parse("example"), false, (String[]) null);
    assertEquals("Integer", writer.registerClass(ExternalClass.of("com.app.Integer")));
    assertEquals("java.lang.Integer", writer.registerClass(ExternalClass.of("java.lang.Integer")));
    assertEquals("Integer", writer.registerClass(ExternalClass.of("com.app.Integer")));
    assertEquals("java.lang.Integer", writer.registerClass(ExternalClass.of("java.lang.Integer")));

    writer.segments.add("class Example {}\n");
    assertEquals("package example;\n\n" //
        + "import com.app.Integer;\n\n" //
        + "class Example {}\n", render(writer));

    writer = new AbstractClassWriter(ClassPackage.parse("example"), false, (String[]) null);
    assertEquals("Integer", writer.registerClass(ExternalClass.of("java.lang.Integer")));
    assertEquals("com.app.Integer", writer.registerClass(ExternalClass.of("com.app.Integer")));
    assertEquals("Integer", writer.registerClass(ExternalClass.of("java.lang.Integer")));
    assertEquals("com.app.Integer", writer.registerClass(ExternalClass.of("com.app.Integer")));

    writer.segments.add("class Example {}\n");
    assertEquals("package example;\n\n" //
        + "class Example {}\n", render(writer));

  }

  @Test
  public void sortsAndGroupsImportsAndAvoidsDuplicates() throws Exception {
    AbstractClassWriter writer = new AbstractClassWriter(ClassPackage.parse("example"), false, (String[]) null);
    assertEquals("Widget", writer.registerClass(ExternalClass.of("com.example.Widget")));
    assertEquals("Set", writer.registerClass(ExternalClass.of("java.util.Set")));
    assertEquals("List", writer.registerClass(ExternalClass.of("com.app.List")));
    assertEquals("java.util.List", writer.registerClass(ExternalClass.of("java.util.List")));
    assertEquals("Thing", writer.registerClass(ExternalClass.of("org.example.Thing")));
    assertEquals("List", writer.registerClass(ExternalClass.of("com.app.List")));
    assertEquals("Item", writer.registerClass(ExternalClass.of("javax.example.Item")));

    assertEquals("java.util.List", writer.registerClass(ExternalClass.of("java.util.List")));

    assertEquals("String", writer.registerClass(ExternalClass.of(String.class)));
    assertEquals("List", writer.registerClass(ExternalClass.of("com.app.List")));
    assertEquals("int[]", writer.registerClass(ExternalClass.of("int[]")));
    writer.segments.add("class Example {}\n");

    assertEquals("package example;\n\n" + "import java.util.Set;\n\n" + "import javax.example.Item;\n\n"
        + "import org.example.Thing;\n\n" + "import com.app.List;\n" + "import com.example.Widget;\n\n"
        + "class Example {}\n", render(writer));
  }

  @Test
  public void usesQualifiedNameForConflictingImports() throws Exception {
    AbstractClassWriter writer = new AbstractClassWriter(ClassPackage.parse("example"), false);

    assertEquals("Date", writer.registerClass(ExternalClass.of("java.util.Date")));
    assertEquals("java.sql.Date[]", writer.registerClass(ExternalClass.of("java.sql.Date[]")));
    assertEquals("package example;\n\nimport java.util.Date;\n\n", render(writer));
  }

  @Test
  public void registersNestedGenericTypesAndArrays() throws Exception {
    AbstractClassWriter writer = new AbstractClassWriter(ClassPackage.parse("example"), false);

    assertEquals("Map<String, List<int[]>>[][]", writer.registerClass(
        ExternalClass.of(TypeParser.parse("java.util.Map<java.lang.String, java.util.List<int[]>>[][]"))));
    assertEquals("package example;\n\nimport java.util.List;\nimport java.util.Map;\n\n", render(writer));
  }

  @Test
  public void propagatesWriterErrors() throws Exception {
    AbstractClassWriter writer = new AbstractClassWriter(ClassPackage.parse("example"), false);
    IOException failure = new IOException("write failed");
    TextWriter output = new TextWriter() {
      @Override
      public void write(String text) throws IOException {
        throw failure;
      }

      @Override
      public void close() {
      }
    };

    assertEquals(failure, assertThrows(IOException.class, () -> writer.writeTo(output)));
  }

  private static String render(AbstractClassWriter writer) throws IOException {
    StringBuilder output = new StringBuilder();
    writer.writeTo(new TextWriter() {
      @Override
      public void write(String text) {
        output.append(text);
      }

      @Override
      public void close() {
      }
    });
    return output.toString();
  }
}