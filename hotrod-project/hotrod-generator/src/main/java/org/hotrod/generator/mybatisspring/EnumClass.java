package org.hotrod.generator.mybatisspring;

import java.io.File;
import java.io.IOException;
import java.util.logging.Logger;

import org.hotrod.config.Constants;
import org.hotrod.config.DaosTag;
import org.hotrod.config.EnumTag.EnumConstant;
import org.hotrod.config.EnumTag.EnumProperty;
import org.hotrod.config.HotRodFragmentConfigTag;
import org.hotrod.exceptions.ControlledException;
import org.hotrod.exceptions.UncontrolledException;
import org.hotrod.generator.FileGenerator;
import org.hotrod.generator.FileGenerator.TextWriter;
import org.hotrod.metadata.EnumDataSetMetadata;
import org.hotrod.utils.AbstractClassWriter.ExternalClass;
import org.hotrod.utils.ClassPackage;
import org.hotrod.utils.ClassWriter;
import org.hotrod.utils.Separator;
import org.nocrala.tools.lang.collector.listcollector.ListWriter;

public class EnumClass {

  // Constants

  private static final Logger log = Logger.getLogger(EnumClass.class.getName());

  // Properties

  private EnumDataSetMetadata metadata;
  private DataSetLayout layout;

  private DaosTag daos;
  @SuppressWarnings("unused")
  private MyBatisSpringGenerator generator;
  private HotRodFragmentConfigTag fragmentConfig;
  private ClassPackage fragmentPackage;

  private ClassPackage primitivesPackage;

  private ClassPackage classPackage;

  private ClassWriter w;

  // Constructor

  public EnumClass(final EnumDataSetMetadata metadata, final DataSetLayout layout, final DaosTag daos,
      final MyBatisSpringGenerator generator) {
    log.fine("init");
    this.metadata = metadata;
    this.layout = layout;
    this.daos = daos;
    this.generator = generator;

    this.fragmentConfig = this.metadata.getFragmentConfig();
    this.fragmentPackage = this.fragmentConfig != null && this.fragmentConfig.getFragmentPackage() != null
        ? this.fragmentConfig.getFragmentPackage()
        : null;
    this.primitivesPackage = this.daos.getPrimitivesPackage(this.fragmentPackage);

    this.classPackage = this.layout.getDAOPrimitivePackage(this.fragmentPackage);

  }

  // Behavior

  public void generate(final FileGenerator fileGenerator) throws UncontrolledException, ControlledException {
    String sourceClassName = this.getClassName() + ".java";

    File dir = this.daos.getPrimitivesPackageDir(this.fragmentPackage);
    File ec = new File(dir, sourceClassName);
    this.w = null;

    try (TextWriter tw = fileGenerator.createWriter(ec)) {

      this.w = new ClassWriter(this.primitivesPackage,
          "// Autogenerated by " + Constants.TOOL_NAME + " -- Do not edit.", "");
      this.writeBody();
      w.writeTo(tw);

    } catch (IOException e) {
      throw new UncontrolledException(
          "Could not generate Java enum class: could not write to file '" + ec.getName() + "'.", e);
    }

  }

  private void writeBody() throws IOException {

    w.println("public enum " + this.getClassName() + " {");
    w.println();

    // prefix, elemPrefix, elemSuffix, separator, suffix
    ListWriter lw = new ListWriter("", "  ", "", ", //\n", ";");
    for (EnumConstant c : this.metadata.getEnumConstants()) {
      lw.add(c.getJavaConstantName() + "(" + ListWriter.render(c.getJavaLiteralValues(), ", ") + ")");
    }
    w.println(lw.toString());
    w.println();

    w.println("  // Properties (table columns)");
    w.println();
    for (EnumProperty p : this.metadata.getProperties()) {
      w.println("  private ", ExternalClass.of(p.getClassName()), " " + p.getName() + ";");
    }
    w.println();

    w.println("  // Constructor");
    w.println();
    w.print("  private " + this.getClassName() + "(");
    Separator sep = new Separator();
    for (EnumProperty p : this.metadata.getProperties()) {
      w.print(sep.render() + "final ", ExternalClass.of(p.getClassName()), " " + p.getName());
    }
    w.println(") {");
    for (EnumProperty p : this.metadata.getProperties()) {
      w.println("    this." + p.getName() + " = " + p.getName() + ";");
    }
    w.println("  }");
    w.println();

    w.println("  // Getters");
    for (EnumProperty p : this.metadata.getProperties()) {
      w.println();
      w.println("  public ", ExternalClass.of(p.getClassName()), " " + p.getGetter() + "() {");
      w.println("    return this." + p.getName() + ";");
      w.println("  }");
    }
    w.println();

    writeCodec();

    w.println("}");
  }

  private void writeCodec() throws IOException {

    EnumProperty valueColumn = this.metadata.getValueColumn();

    w.println("  // Encode & Decode");
    w.println();
    w.println("  public static ",
        ExternalClass.of(this.getClassName()) + " decode(final " + valueColumn.getClassName() + " value) {");
    w.println("    if (value == null) {");
    w.println("      return null;");
    w.println("    }");
    w.println("    for (", ExternalClass.of(this.getClassName()) + " e : ", ExternalClass.of(this.getClassName()),
        ".values()) {");
    w.println("      if (e." + valueColumn.getName() + ".equals(value)) {");
    w.println("        return e;");
    w.println("      }");
    w.println("    }");
    w.println("    throw new IllegalArgumentException(");
    w.println("        \"Invalid " + this.metadata.getId().getCanonicalSQLName() + " " + valueColumn.getName()
        + " value (\" + value + \"). There's no enum constant for this value.\\n\\n"
        + "***** Maybe the <enum> table data has changed, and the <enum> table needs to be regenerated *****\\n\");");
    w.println("  }");
    w.println();
    w.println("  public static ", ExternalClass.of(valueColumn.getClassName()), " encode(final ",
        ExternalClass.of(this.getClassName()) + " e) {");
    w.println("    return e == null ? null : e." + valueColumn.getName() + ";");
    w.println("  }");
    w.println();

  }

  // Getters

  public String getClassName() {
    return this.metadata.getJavaClassName();
  }

  public String getFullClassName() {
    return this.classPackage.getFullClassName(this.getClassName());
  }

  public EnumProperty getValueColumn() {
    return this.metadata.getValueColumn();
  }

}
