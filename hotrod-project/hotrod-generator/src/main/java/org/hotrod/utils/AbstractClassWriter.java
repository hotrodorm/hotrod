package org.hotrod.utils;

import java.io.IOException;
import java.util.ArrayList;
import java.util.Collections;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.logging.Logger;

import org.hotrod.BuildInformation;
import org.hotrod.config.Constants;
import org.hotrod.generator.FileGenerator.TextWriter;
import org.hotrod.metadata.TypeParser.Type;

public class AbstractClassWriter {

  @SuppressWarnings("unused")
  public static final Logger log = Logger.getLogger(AbstractClassWriter.class.getName());

  private String[] headerLines;
  private ClassPackage classPackage;

  protected List<String> segments;
  private LinkedHashMap<String, String> importCode; // import name / code name (full/simple)
  private Map<String, String> simpleImport; // simple name / import name

  public AbstractClassWriter(final ClassPackage classPackage, final String... headerLines) {
    this.headerLines = headerLines;
    this.classPackage = classPackage;
    this.importCode = new LinkedHashMap<>();
    this.simpleImport = new LinkedHashMap<>();
    this.segments = new ArrayList<>();
  }

  public void println() {
    this.segments.add("\n");
  }

  public void writeTo(final TextWriter w) throws IOException {

    w.write("// Generated by " + Constants.TOOL_NAME + " " + BuildInformation.VERSION);
//    w.write(" on " + SUtil.format(LocalDateTime.now()));
    w.write(" - Do not edit");
    w.write("\n\n");

    if (this.headerLines != null) {
      for (String h : this.headerLines) {
        w.write(h + "\n");
      }
    }

    w.write("package " + this.classPackage.getPackage() + ";\n\n");

    ImportSorter is = new ImportSorter();
    for (String i : this.importCode.keySet()) {
      String code = this.importCode.get(i);
      if (!i.equals(code)) {
        is.register(i);
      }
    }
    is.writeTo(w);

    for (String s : this.segments) {
      w.write(s);
    }

  }

  private class ImportSorter {

    private List<String> java = new ArrayList<>();
    private List<String> javax = new ArrayList<>();
    private List<String> org = new ArrayList<>();
    private List<String> other = new ArrayList<>();

    public void register(final String c) {
      if (c == null) {
        return;
      } else if (c.startsWith("java.")) {
        this.java.add(c);
      } else if (c.startsWith("javax.")) {
        this.javax.add(c);
      } else if (c.startsWith("org.")) {
        this.org.add(c);
      } else {
        this.other.add(c);
      }
    }

    public void writeTo(final TextWriter w) throws IOException {
      this.writeListTo(this.java, w);
      this.writeListTo(this.javax, w);
      this.writeListTo(this.org, w);
      this.writeListTo(this.other, w);
    }

    private void writeListTo(final List<String> list, final TextWriter w) throws IOException {
      if (!list.isEmpty()) {
        Collections.sort(list);
        for (String i : list) {
          w.write("import " + i + ";\n");
        }
        w.write("\n");
      }
    }

  }

  protected String registerClass(final ExternalClass pc) {

    if (pc.type == null) {

      String importName = pc.getImportName();
      String baseClass = pc.getBaseClass();
      String shortCodeName = pc.getShortCodeName();
      String longCodeName = pc.getLongCodeName();
      return registerImportName(importName, baseClass, shortCodeName, longCodeName);

    } else {

      StringBuilder sb = new StringBuilder();
      register(pc.type, sb);
      return sb.toString();

    }

  }

  private void register(Type t, StringBuilder sb) {

    int ld = t.base.lastIndexOf(".");

    String importName = t.base;
    String baseClass = t.base.substring(ld + 1);
    String shortCodeName = t.base.substring(ld + 1);
    String longCodeName = t.base;
    String s = registerImportName(importName, baseClass, shortCodeName, longCodeName);
    sb.append(s);

    if (!t.generics.isEmpty()) {
      sb.append("<");
    }
    Separator sep = Separator.of(", ");
    for (Type g : t.generics) {
      sb.append(sep.render());
      register(g, sb);
    }
    if (!t.generics.isEmpty()) {
      sb.append(">");
    }

    for (int i = 0; i < t.arrayDepth; i++) {
      sb.append("[]");
    }

  }

  private String registerImportName(String importname, String baseClass, String shortCodeName, String longCodeName) {
    if (importname.startsWith("java.lang.") || isPrimitive(baseClass)) {
      // skip registering
      return shortCodeName;
    }

    String registeredCodeName = this.importCode.get(importname);
    if (registeredCodeName != null) {
      // already registered
      return shortCodeName;
    }

    // Not registered

    String otherSimpleName = this.simpleImport.get(baseClass);
    if (otherSimpleName == null) {
      this.importCode.put(importname, baseClass);
      this.simpleImport.put(baseClass, importname);
      return shortCodeName;
    } else {
      this.importCode.put(importname, importname);
      return longCodeName;
    }
  }

  private boolean isPrimitive(String c) {
    return "byte".equals(c) //
        || "short".equals(c) //
        || "int".equals(c) //
        || "long".equals(c) //
        || "float".equals(c) //
        || "double".equals(c) //
        || "boolean".equals(c) //
        || "char".equals(c);
  }

  public static class ExternalClass {

    private String original;
    private String generics;
    private String arrays;
    private String importName;
    private String baseClass;
    private String shortCodeName;
    private String longCodeName;

    private Type type;

    public static ExternalClass of(String c) {
      return new ExternalClass(c);
    }

    public static ExternalClass of(Class<?> c) {
      return new ExternalClass(c.getCanonicalName());
    }

    public static ExternalClass of(Type t) {
      return new ExternalClass(t);
    }

    private ExternalClass(Type t) {
      this.original = null;
      this.type = t;
    }

    private ExternalClass(String c) {
      this.original = c;
      this.type = null;

      String gfree;
      int l = c.indexOf("<");
      int g = c.lastIndexOf(">");
      if (l != -1 && g != -1) {
        this.generics = c.substring(l, g + 1);
        gfree = c.substring(0, l) + c.substring(g + 1);
      } else {
        this.generics = null;
        gfree = c;
      }

      int b = gfree.indexOf("[");
      if (b != -1) {
        this.arrays = gfree.substring(b);
        this.importName = gfree.substring(0, b);
      } else {
        this.arrays = null;
        this.importName = gfree;
      }

      int dot = importName.lastIndexOf('.');
      this.baseClass = dot == -1 ? importName : importName.substring(dot + 1);
      this.shortCodeName = this.baseClass + coalesce(this.generics, "") + coalesce(this.arrays, "");
      this.longCodeName = this.importName + coalesce(this.generics, "") + coalesce(this.arrays, "");

    }

    private String coalesce(String a, String b) {
      return a != null ? a : b;
    }

    public String toString() {
      return "orig: " + this.original + " - generics: " + this.generics + " - arrays: " + this.arrays
          + " - importName: " + this.importName + " - baseClass: " + this.baseClass + " - shortCodeName: "
          + this.shortCodeName;
    }

    public String getOriginal() {
      return original;
    }

    public String getGenerics() {
      return generics;
    }

    public String getArrays() {
      return arrays;
    }

    public String getImportName() {
      return importName;
    }

    public String getBaseClass() {
      return baseClass;
    }

    public String getShortCodeName() {
      return this.shortCodeName;
    }

    public String getLongCodeName() {
      return longCodeName;
    }

  }

}
